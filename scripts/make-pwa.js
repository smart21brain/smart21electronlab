// Writes src/sw.js (service worker) with the list of every file in src/, so the app works offline once installed from a browser.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', 'src'); const files = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f), st = fs.statSync(p); if (st.isDirectory()) walk(p); else if (!/sw\.js$|\.map$/.test(f)) files.push(path.relative(root, p).split(path.sep).join('/')); } })(root);
const version = require('../package.json').version;
const sw = `/* generated by scripts/make-pwa.js: do not edit */
const CACHE = 'smart21-electrolab-${version}';
const ASSETS = ${JSON.stringify(['./'].concat(files.sort()), null, 1)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => { if (e.request.method !== 'GET') return; e.respondWith(caches.match(e.request).then(r => r || fetch(e.request))); });
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw); console.log('sw.js written with ' + files.length + ' files');
